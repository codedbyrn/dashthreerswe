export interface DynamicIconProps extends IconProps {
  name: string;
}

export const Icon = ({ name, size = 20, className, ...props }: DynamicIconProps) => {
  const IconComponent = iconRegistry[name];
  if (!IconComponent) {
    // Default placeholder circle if icon not found
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        className={className}
        {...props}
      >
        <circle cx="12" cy="12" r="10" />
      </svg>
    );
  }
  return <IconComponent size={size} className={className} {...props} />;
};
