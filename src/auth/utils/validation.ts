// تعبير نمطي (Regex) للتحقق من أن كلمة المرور تحتوي على:
// - طول لا يقل عن 9 أحرف (?=.{9,})
// - حرف كبير واحد على الأقل (?=.*[A-Z])
// - حرف صغير واحد على الأقل (?=.*[a-z])
// - رقم واحد على الأقل (?=.*\d)
// - رمز خاص واحد على الأقل (?=.*[!@#$%^&*(),.?":{}|<>])
export const passwordRegex = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[!@#$%^&*(),.?":{}|<>]).{9,}$/;

// دالة للتحقق من صحة كلمة المرور الممررة وإرجاع رسالة خطأ إن وجدت
export const validatePassword = (password: string): string | null => {
  if (!password) return "كلمة المرور مطلوبة"; // التحقق من وجود قيمة مدخلة
  if (password.length < 9) return "كلمة المرور يجب أن تكون 9 أحرف على الأقل"; // التحقق من الطول الأدنى
  if (!/[A-Z]/.test(password)) return "يجب أن تحتوي على حرف كبير واحد على الأقل"; // التحقق من وجود حرف كبير
  if (!/[a-z]/.test(password)) return "يجب أن تحتوي على حرف صغير واحد على الأقل"; // التحقق من وجود حرف صغير
  if (!/\d/.test(password)) return "يجب أن تحتوي على رقم واحد على الأقل"; // التحقق من وجود أرقام
  if (!/[!@#$%^&*(),.?":{}|<>]/.test(password)) return "يجب أن تحتوي على رمز خاص واحد على الأقل"; // التحقق من وجود رمز خاص للتعقيد
  
  return null; // إرجاع القيمة الخالية (null) يعني أن كلمة المرور صالحة تماماً
};

// دالة للتحقق من صحة البريد الإلكتروني المدخل وإرجاع خطأ إن وجد
export const validateEmail = (email: string): string | null => {
  if (!email) return "البريد الإلكتروني مطلوب"; // التحقق من وجود البريد المدخل
  // التحقق باستخدام Regex لضمان أن التركيبة تحتوي على @ ونقطة في مكان صحيح
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return "البريد الإلكتروني غير صالح";
  return null; // البريد صالح تماماً
};
